/**
 * Assessment request validation.
 *
 * Same shape as the other validators here: a pure `*Input(body)` function that
 * returns an array of `{ field, message }`, plus a `toMiddleware` wrapper. Pure
 * because the interesting cases — a duplicate question index, an option index of
 * -1 — are worth testing without building a request object.
 *
 * WHAT IS DELIBERATELY NOT VALIDATED HERE. Whether question 7 exists on *this*
 * attempt, and whether it has that many options. The validator cannot know: the
 * paper lives on the document. assessment.service.js checks both against the
 * snapshot and raises 400 with the same envelope. Validating shape here and
 * membership there keeps each check where the information actually is.
 */

import AppError from '../utils/AppError.js';
import {
  DEFAULT_QUESTION_COUNT,
  MAX_QUESTION_COUNT,
  MIN_QUESTION_COUNT,
} from '../constants/assessments.js';

const OBJECT_ID_PATTERN = /^[a-f\d]{24}$/i;

export const isObjectIdLike = (value) =>
  typeof value === 'string' && OBJECT_ID_PATTERN.test(value.trim());

const MAX_ANSWERS = MAX_QUESTION_COUNT;

/**
 * Fields a client must not send when starting an assessment.
 *
 * `studentId` is the important one: it comes from the token, and accepting it
 * from the body would make "assess someone else" expressible. Rejecting loudly
 * rather than ignoring silently, so a client author finds out immediately.
 */
const REJECTED_START_FIELDS = Object.freeze({
  studentId: 'The student is taken from your account and cannot be set directly.',
  userId: 'The student is taken from your account and cannot be set directly.',
  questions: 'Questions are generated by the server and cannot be supplied.',
  skillScores: 'Scores are calculated by the server and cannot be supplied.',
  overallScore: 'Scores are calculated by the server and cannot be supplied.',
  status: 'The status is managed by the server.',
});

const checkRejectedFields = (body, errors) => {
  for (const [field, message] of Object.entries(REJECTED_START_FIELDS)) {
    if (body[field] !== undefined) errors.push({ field, message });
  }
};

export const validateStartAssessmentInput = (body = {}) => {
  const errors = [];

  checkRejectedFields(body, errors);

  // Optional: a student with a stated career goal needs neither field.
  if (body.careerRoleId !== undefined && body.careerRoleId !== null && body.careerRoleId !== '') {
    if (!isObjectIdLike(body.careerRoleId)) {
      errors.push({ field: 'careerRoleId', message: 'Please choose a career role from the list.' });
    }
  }

  if (body.questionCount !== undefined && body.questionCount !== null) {
    const count = Number(body.questionCount);
    if (!Number.isInteger(count) || count < MIN_QUESTION_COUNT || count > MAX_QUESTION_COUNT) {
      errors.push({
        field: 'questionCount',
        message: `Choose between ${MIN_QUESTION_COUNT} and ${MAX_QUESTION_COUNT} questions (default ${DEFAULT_QUESTION_COUNT}).`,
      });
    }
  }

  return errors;
};

/**
 * `answers: [{ questionIndex, optionIndex }]`.
 *
 * An empty array is allowed. Submitting a blank paper scores zero, which is the
 * honest result — refusing the submission would leave the attempt open forever
 * and block the student from starting another.
 */
export const validateSubmitAssessmentInput = (body = {}) => {
  const errors = [];

  if (body.answers === undefined) {
    errors.push({ field: 'answers', message: 'Send an answers array, even if it is empty.' });
    return errors;
  }

  if (!Array.isArray(body.answers)) {
    errors.push({ field: 'answers', message: 'Answers must be an array.' });
    return errors;
  }

  if (body.answers.length > MAX_ANSWERS) {
    errors.push({
      field: 'answers',
      message: `An assessment cannot have more than ${MAX_ANSWERS} answers.`,
    });
    return errors;
  }

  const seenQuestionIndexes = new Set();

  body.answers.forEach((answer, position) => {
    if (!answer || typeof answer !== 'object' || Array.isArray(answer)) {
      errors.push({
        field: `answers[${position}]`,
        message: 'Each answer must be an object with questionIndex and optionIndex.',
      });
      return;
    }

    const questionIndex = Number(answer.questionIndex);
    const optionIndex = Number(answer.optionIndex);

    if (!Number.isInteger(questionIndex) || questionIndex < 0) {
      errors.push({
        field: `answers[${position}].questionIndex`,
        message: 'questionIndex must be a whole number of zero or more.',
      });
    } else if (seenQuestionIndexes.has(questionIndex)) {
      // Two answers to one question means the last write wins silently, and a
      // student would have no way to know which was recorded.
      errors.push({
        field: `answers[${position}].questionIndex`,
        message: `Question ${questionIndex} was answered more than once.`,
      });
    } else {
      seenQuestionIndexes.add(questionIndex);
    }

    if (!Number.isInteger(optionIndex) || optionIndex < 0) {
      errors.push({
        field: `answers[${position}].optionIndex`,
        message: 'optionIndex must be a whole number of zero or more.',
      });
    }
  });

  return errors;
};

export const validateObjectIdParam = (paramName) => (req, _res, next) => {
  const value = req.params[paramName];

  if (!isObjectIdLike(value)) {
    return next(
      AppError.badRequest('Validation failed', [
        { field: paramName, message: 'That is not a valid id.' },
      ]),
    );
  }

  return next();
};

const toMiddleware = (validator) => (req, _res, next) => {
  const errors = validator(req.body ?? {});

  if (errors.length > 0) return next(AppError.badRequest('Validation failed', errors));

  return next();
};

export const validateStartAssessment = toMiddleware(validateStartAssessmentInput);
export const validateSubmitAssessment = toMiddleware(validateSubmitAssessmentInput);

export const ASSESSMENT_LIMITS = Object.freeze({
  minQuestionCount: MIN_QUESTION_COUNT,
  maxQuestionCount: MAX_QUESTION_COUNT,
  defaultQuestionCount: DEFAULT_QUESTION_COUNT,
});
