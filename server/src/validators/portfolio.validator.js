/**
 * Portfolio request validators.
 *
 * SAME CONTRACT AS studentProfile.validator.js: each exported middleware either
 * calls `next()` or calls `next(AppError.badRequest('Validation failed', errors))`
 * with a list of `{field, message}` entries. The error handler turns that into the
 * standard failure envelope, so a client can put each message beside its input.
 *
 * TWO THINGS ARE ENFORCED BY ABSENCE RATHER THAN BY CHECKS, which is stronger:
 *
 *   `studentId` / `userId` — no validator here reads them, and no service accepts
 *   them. Ownership comes from `req.user.id`. "Student A writes to student B's
 *   portfolio" is not a request that can be expressed, so it is not a check that
 *   can be forgotten.
 *
 *   `verificationStatus` — absent from every whitelist below. A student cannot
 *   mark their own record verified because the field is not in the set of fields
 *   a request may carry. `REJECTED_FIELDS` turns an attempt into an explicit 400
 *   rather than silently dropping it, so the refusal is visible.
 */

import {
  ACHIEVEMENT_TYPE_VALUES,
  ALLOWED_DOCUMENT_MIME_VALUES,
  DOCUMENT_TYPE_VALUES,
  EXPERIENCE_TYPE_VALUES,
  PORTFOLIO_LIMITS,
  UPLOAD_LIMITS,
} from '../constants/portfolio.js';
import AppError from '../utils/AppError.js';

/**
 * Fields the server owns. Sending one is a 400 with an explanation, not a silent
 * drop — a client that thinks it can set a verification status should be told it
 * cannot, otherwise the bug hides until a demo.
 */
const REJECTED_FIELDS = Object.freeze({
  verificationStatus:
    'Verification status is set by reviewers, not by students. New records start as pending.',
  studentId: 'Your identity comes from your login, so studentId is not accepted here.',
  userId: 'Your identity comes from your login, so userId is not accepted here.',
  document: 'Attach a file with the upload endpoint, not as a JSON field.',
  fileUrl: 'File locations are generated by the server.',
  fileName: 'File names are generated by the server.',
});

const rejectServerOwnedFields = (body, errors) => {
  for (const [field, message] of Object.entries(REJECTED_FIELDS)) {
    if (body[field] !== undefined) errors.push({ field, message });
  }
};

// --- primitive checks ------------------------------------------------------
// Shaped like studentProfile.validator.js's helpers so both files read the same.
//
// EXPORTED SINCE STEP 7, and nothing else about them changed. `academician.validator.js`
// validates the same primitive kinds of value — a required name, an optional
// description, a past date, a member of a closed set — and re-typing these seven
// functions there would have meant two definitions of "is this a valid date" that
// could drift apart without either one looking wrong. The precedent is
// `validateObjectIdParam`, which three route files already import from
// studentProfile.validator.js.
//
// They are pure and take their limits as arguments, so exporting them widens no
// surface: the only shared assumption is `checkOptionalUrl`'s length cap, which
// reads PORTFOLIO_LIMITS.maxUrlLength. That equals ACADEMICIAN_LIMITS.maxUrlLength
// today and the Step 7 verifier asserts it, so the message quotes the right number
// for both callers.

export const checkRequiredString = (value, { field, max, label }, errors) => {
  if (value === undefined || value === null) {
    errors.push({ field, message: `${label} is required.` });
    return;
  }

  if (typeof value !== 'string') {
    errors.push({ field, message: `${label} must be text.` });
    return;
  }

  const trimmed = value.trim();
  if (trimmed.length === 0) {
    errors.push({ field, message: `${label} cannot be empty.` });
    return;
  }

  if (trimmed.length > max) {
    errors.push({ field, message: `${label} cannot exceed ${max} characters.` });
  }
};

export const checkOptionalString = (value, { field, max, label }, errors) => {
  if (value === undefined || value === null || value === '') return;

  if (typeof value !== 'string') {
    errors.push({ field, message: `${label} must be text.` });
    return;
  }

  if (value.trim().length > max) {
    errors.push({ field, message: `${label} cannot exceed ${max} characters.` });
  }
};

/**
 * Accepts anything `new Date()` parses, and normalises nothing — the service
 * converts, this only judges. An explicit `null` is allowed so a client can
 * clear a date it previously set.
 */
export const checkDate = (value, { field, label, required = false }, errors) => {
  if (value === undefined || value === null || value === '') {
    if (required) errors.push({ field, message: `${label} is required.` });
    return;
  }

  if (typeof value !== 'string' && !(value instanceof Date) && typeof value !== 'number') {
    errors.push({ field, message: `${label} must be a date.` });
    return;
  }

  const parsed = new Date(value);
  if (Number.isNaN(parsed.getTime())) {
    errors.push({ field, message: `${label} is not a valid date.` });
    return;
  }

  // A portfolio records what happened, not what is planned. A tolerance of one
  // day absorbs timezone differences between the browser and the server rather
  // than rejecting "today" for a student ahead of UTC.
  const tomorrow = new Date(Date.now() + 24 * 60 * 60 * 1000);
  if (parsed > tomorrow) {
    errors.push({ field, message: `${label} cannot be in the future.` });
  }
};

export const checkBoolean = (value, { field, label }, errors) => {
  if (value === undefined || value === null) return;
  if (typeof value !== 'boolean') {
    errors.push({ field, message: `${label} must be true or false.` });
  }
};

export const checkEnum = (value, { field, label, values, required = false }, errors) => {
  if (value === undefined || value === null || value === '') {
    if (required) errors.push({ field, message: `${label} is required.` });
    return;
  }

  if (!values.includes(value)) {
    errors.push({ field, message: `${label} must be one of: ${values.join(', ')}.` });
  }
};

/**
 * A URL, if given at all.
 *
 * Only http and https are accepted. `javascript:alert(1)` parses perfectly well
 * as a URL, and this value ends up in an anchor's href — so the scheme check is
 * the thing standing between a stored URL and stored XSS.
 */
export const checkOptionalUrl = (value, { field, label }, errors) => {
  if (value === undefined || value === null || value === '') return;

  if (typeof value !== 'string') {
    errors.push({ field, message: `${label} must be text.` });
    return;
  }

  if (value.trim().length > PORTFOLIO_LIMITS.maxUrlLength) {
    errors.push({
      field,
      message: `${label} cannot exceed ${PORTFOLIO_LIMITS.maxUrlLength} characters.`,
    });
    return;
  }

  let parsed;
  try {
    parsed = new URL(value.trim());
  } catch {
    errors.push({ field, message: `${label} must be a full URL starting with https://.` });
    return;
  }

  if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') {
    errors.push({ field, message: `${label} must start with http:// or https://.` });
  }
};

/** A list of short free-text tags: technologies, skills used. */
export const checkStringArray = (value, { field, label, maxItems, maxLength }, errors) => {
  if (value === undefined || value === null) return;

  if (!Array.isArray(value)) {
    errors.push({ field, message: `${label} must be a list.` });
    return;
  }

  if (value.length > maxItems) {
    errors.push({ field, message: `Please list at most ${maxItems} ${label.toLowerCase()}.` });
    return;
  }

  for (const entry of value) {
    if (typeof entry !== 'string' || entry.trim().length === 0) {
      errors.push({ field, message: `Every entry in ${label.toLowerCase()} must be text.` });
      return;
    }

    if (entry.trim().length > maxLength) {
      errors.push({
        field,
        message: `Each entry in ${label.toLowerCase()} must be ${maxLength} characters or fewer.`,
      });
      return;
    }
  }

  const normalised = value.map((entry) => entry.trim().toLowerCase());
  if (new Set(normalised).size !== normalised.length) {
    errors.push({ field, message: `${label} contains duplicates.` });
  }
};

/**
 * Rejects a body with nothing in it.
 *
 * A PATCH with an empty object would otherwise "succeed" while changing nothing,
 * which reads to the student as a save that silently failed.
 */
const checkNotEmpty = (body, allowedFields, errors) => {
  const provided = allowedFields.filter((field) => body[field] !== undefined);
  if (provided.length === 0) {
    errors.push({
      field: 'body',
      message: `Send at least one field to update: ${allowedFields.join(', ')}.`,
    });
  }
};

const toMiddleware = (validator) => (req, _res, next) => {
  const errors = validator(req.body ?? {});
  if (errors.length > 0) return next(AppError.badRequest('Validation failed', errors));
  return next();
};

// --- projects --------------------------------------------------------------

export const PROJECT_FIELDS = Object.freeze([
  'title',
  'description',
  'technologies',
  'role',
  'githubUrl',
  'liveUrl',
  'startDate',
  'endDate',
  'isOngoing',
]);

const validateProjectBody = (body, { isCreate }) => {
  const errors = [];
  rejectServerOwnedFields(body, errors);

  if (isCreate) {
    checkRequiredString(
      body.title,
      { field: 'title', max: PORTFOLIO_LIMITS.maxTitleLength, label: 'Project title' },
      errors,
    );
    checkRequiredString(
      body.description,
      {
        field: 'description',
        max: PORTFOLIO_LIMITS.maxDescriptionLength,
        label: 'Description',
      },
      errors,
    );
  } else {
    checkNotEmpty(body, PROJECT_FIELDS, errors);
    // On update these are optional, but if sent they must still be non-empty:
    // clearing a required field through a PATCH would leave an invalid record.
    if (body.title !== undefined) {
      checkRequiredString(
        body.title,
        { field: 'title', max: PORTFOLIO_LIMITS.maxTitleLength, label: 'Project title' },
        errors,
      );
    }
    if (body.description !== undefined) {
      checkRequiredString(
        body.description,
        {
          field: 'description',
          max: PORTFOLIO_LIMITS.maxDescriptionLength,
          label: 'Description',
        },
        errors,
      );
    }
  }

  checkStringArray(
    body.technologies,
    {
      field: 'technologies',
      label: 'Technologies',
      maxItems: PORTFOLIO_LIMITS.maxTechnologies,
      maxLength: PORTFOLIO_LIMITS.maxTechnologyLength,
    },
    errors,
  );
  checkOptionalString(
    body.role,
    { field: 'role', max: PORTFOLIO_LIMITS.maxRoleLength, label: 'Your role' },
    errors,
  );
  checkOptionalUrl(body.githubUrl, { field: 'githubUrl', label: 'Repository URL' }, errors);
  checkOptionalUrl(body.liveUrl, { field: 'liveUrl', label: 'Live URL' }, errors);
  checkDate(body.startDate, { field: 'startDate', label: 'Start date' }, errors);
  checkDate(body.endDate, { field: 'endDate', label: 'End date' }, errors);
  checkBoolean(body.isOngoing, { field: 'isOngoing', label: 'Ongoing' }, errors);

  // Caught here as well as in the model so the student gets a field-attached
  // message instead of a generic "Validation failed" from Mongoose.
  if (!body.isOngoing && body.startDate && body.endDate) {
    const start = new Date(body.startDate);
    const end = new Date(body.endDate);
    if (!Number.isNaN(start.getTime()) && !Number.isNaN(end.getTime()) && end < start) {
      errors.push({ field: 'endDate', message: 'The end date cannot be before the start date.' });
    }
  }

  return errors;
};

export const validateCreateProject = toMiddleware((body) =>
  validateProjectBody(body, { isCreate: true }),
);

export const validateUpdateProject = toMiddleware((body) =>
  validateProjectBody(body, { isCreate: false }),
);

