/**
 * Decodes the percent-encoded `X-File-Name` header.
 *
 * WHY IT IS ENCODED AT ALL. HTTP header values cannot carry arbitrary Unicode —
 * browsers throw outright when asked to set one — so the client sends
 * `encodeURIComponent(file.name)`. Without this decode, a resume named in Hindi or
 * containing an em dash would be stored and shown as `%E0%A4%B0...`.
 *
 * The try/catch is not decoration: `decodeURIComponent('%')` throws
 * `URIError`, and a malformed header is exactly the kind of thing a fuzzer sends.
 * A crafted header must not become a 500, so a value that will not decode falls
 * back to the raw string and `document.service.js` sanitises it either way.
 *
 * This is display text only. It never touches the filesystem — storage names are
 * generated server-side — so a hostile value here can at worst look odd in a list.
 */
const decodeDisplayName = (value) => {
  if (typeof value !== 'string' || value.length === 0) return 'document';

  try {
    return decodeURIComponent(value);
  } catch {
    return value;
  }
};

/**
 * Validates upload HEADERS before a single byte of the body is read.
 *
 * Order matters for a reason: rejecting an oversized or wrong-typed upload here
 * means the request never reaches the code that buffers it. The bytes themselves
 * are re-checked afterwards — `Content-Type` and `Content-Length` are claims made
 * by the client, and `document.service.js` verifies both against reality.
 *
 * Upload metadata travels in headers rather than a JSON body because the body IS
 * the file: there is no multipart parser available, so the request carries raw
 * bytes and nothing else.
 */
export const validateDocumentUpload = (req, _res, next) => {
  const errors = [];

  const mimeType = String(req.headers['content-type'] ?? '')
    .split(';')[0]
    .trim()
    .toLowerCase();

  if (!mimeType) {
    errors.push({ field: 'contentType', message: 'A Content-Type header is required.' });
  } else if (!ALLOWED_DOCUMENT_MIME_VALUES.includes(mimeType)) {
    errors.push({
      field: 'contentType',
      message: `Accepted file types: ${ALLOWED_DOCUMENT_MIME_VALUES.join(', ')}.`,
    });
  }

  const declaredLength = Number(req.headers['content-length']);
  if (Number.isFinite(declaredLength) && declaredLength > UPLOAD_LIMITS.maxFileBytes) {
    errors.push({
      field: 'file',
      message: `Files must be ${Math.round(UPLOAD_LIMITS.maxFileBytes / (1024 * 1024))} MB or smaller.`,
    });
  }

  if (Number.isFinite(declaredLength) && declaredLength === 0) {
    errors.push({ field: 'file', message: 'That file is empty.' });
  }

  const documentType = req.query.documentType ?? req.headers['x-document-type'];
  if (documentType !== undefined && !DOCUMENT_TYPE_VALUES.includes(String(documentType))) {
    errors.push({
      field: 'documentType',
      message: `Document type must be one of: ${DOCUMENT_TYPE_VALUES.join(', ')}.`,
    });
  }

  if (errors.length > 0) return next(AppError.badRequest('Validation failed', errors));

  // Stashed so the controller does not re-parse the header. Not on `req.body` —
  // that is the file's territory on these routes.
  req.uploadMeta = {
    mimeType,
    originalName: decodeDisplayName(req.headers['x-file-name'] ?? req.query.fileName),
  };

  return next();
};

/**
 * Guards the download route's `:fileName`.
 *
 * A loose sanity check only — `document.service.js` does the authoritative
 * pattern-and-containment validation, and the service will not resolve a name
 * that is not already recorded in the caller's own profile. This exists so an
 * obviously hostile path is rejected before any lookup happens.
 */
export const validateStoredFileNameParam = (req, _res, next) => {
  const { fileName } = req.params;

  if (
    typeof fileName !== 'string' ||
    fileName.length === 0 ||
    fileName.length > UPLOAD_LIMITS.maxFileNameLength ||
    fileName.includes('/') ||
    fileName.includes('\\') ||
    fileName.includes('..') ||
    !/^[A-Za-z0-9._-]+$/.test(fileName)
  ) {
    return next(AppError.notFound('Document not found.'));
  }

  return next();
};

