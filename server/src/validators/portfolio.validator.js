export const CERTIFICATION_FIELDS = Object.freeze([
  'title',
  'issuingOrganization',
  'issueDate',
  'expiryDate',
  'credentialId',
  'credentialUrl',
]);

const validateCertificationBody = (body, { isCreate }) => {
  const errors = [];
  rejectServerOwnedFields(body, errors);

  if (isCreate) {
    checkRequiredString(
      body.title,
      { field: 'title', max: PORTFOLIO_LIMITS.maxTitleLength, label: 'Certification title' },
      errors,
    );
    checkRequiredString(
      body.issuingOrganization,
      {
        field: 'issuingOrganization',
        max: PORTFOLIO_LIMITS.maxOrganizationLength,
        label: 'Issuing organisation',
      },
      errors,
    );
  } else {
    checkNotEmpty(body, CERTIFICATION_FIELDS, errors);
    if (body.title !== undefined) {
      checkRequiredString(
        body.title,
        { field: 'title', max: PORTFOLIO_LIMITS.maxTitleLength, label: 'Certification title' },
        errors,
      );
    }
    if (body.issuingOrganization !== undefined) {
      checkRequiredString(
        body.issuingOrganization,
        {
          field: 'issuingOrganization',
          max: PORTFOLIO_LIMITS.maxOrganizationLength,
          label: 'Issuing organisation',
        },
        errors,
      );
    }
  }

  checkDate(body.issueDate, { field: 'issueDate', label: 'Issue date' }, errors);

  // Deliberately NOT passed through checkDate: an expiry is the one date in the
  // portfolio that is *supposed* to be in the future.
  if (body.expiryDate !== undefined && body.expiryDate !== null && body.expiryDate !== '') {
    const parsed = new Date(body.expiryDate);
    if (Number.isNaN(parsed.getTime())) {
      errors.push({ field: 'expiryDate', message: 'Expiry date is not a valid date.' });
    } else if (body.issueDate) {
      const issued = new Date(body.issueDate);
      if (!Number.isNaN(issued.getTime()) && parsed < issued) {
        errors.push({
          field: 'expiryDate',
          message: 'The expiry date cannot be before the issue date.',
        });
      }
    }
  }

  checkOptionalString(
    body.credentialId,
    {
      field: 'credentialId',
      max: PORTFOLIO_LIMITS.maxCredentialIdLength,
      label: 'Credential ID',
    },
    errors,
  );
  checkOptionalUrl(
    body.credentialUrl,
    { field: 'credentialUrl', label: 'Credential URL' },
    errors,
  );

  return errors;
};

export const validateCreateCertification = toMiddleware((body) =>
  validateCertificationBody(body, { isCreate: true }),
);

export const validateUpdateCertification = toMiddleware((body) =>
  validateCertificationBody(body, { isCreate: false }),
);

