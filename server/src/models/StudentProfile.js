/**
 * Keeps "ongoing" and "has an end date" from contradicting each other, and
 * rejects an end that precedes its start.
 *
 * Applied as a subdocument validator rather than checked in the service, so the
 * invariant holds however the document was built — including from the seed.
 * `ongoingKey` differs between projects (`isOngoing`) and experience
 * (`isCurrent`) because each reads naturally in its own context.
 */
const applyDateOrderValidation = (schema, ongoingKey) => {
  schema.pre('validate', function checkDateOrder(next) {
    if (this[ongoingKey]) {
      // Trusting the flag over the date: the student ticked "still going".
      this.endDate = null;
      return next();
    }

    if (this.startDate && this.endDate && this.endDate < this.startDate) {
      this.invalidate('endDate', 'The end date cannot be before the start date');
    }

    return next();
  });
};

applyDateOrderValidation(projectSchema, 'isOngoing');
applyDateOrderValidation(experienceSchema, 'isCurrent');

certificationSchema.pre('validate', function checkExpiry(next) {
  if (this.issueDate && this.expiryDate && this.expiryDate < this.issueDate) {
    this.invalidate('expiryDate', 'The expiry date cannot be before the issue date');
  }
  return next();
});

