/**
 * StudentProfile model — everything about a student that is NOT identity.
 *
 * Relationship design (his section 13 asks for this to be deliberate):
 *
 *   User 1───1 StudentProfile          userId, unique index
 *   StudentProfile.skills[].skillId  ──> Skill        (many refs, shared catalogue)
 *   StudentProfile.targetRoles[].roleId ──> CareerRole (many refs, shared catalogue)
 *
 * WHY A SEPARATE COLLECTION rather than more fields on User. Authentication data
 * (name, email, password, role, isActive) is read on every single request by the
 * auth middleware; profile data is read only on profile screens. Keeping them
 * apart means a login does not drag a bio, skill list and career goals through
 * bcrypt-adjacent code, and the password hash lives nowhere near data we send to
 * other students later. It is also what TRD.md section 7 lays out: `Users` and
 * `StudentProfiles` are distinct collections.
 *
 * WHY EMBED skills and targetRoles rather than give them their own collections.
 * They have no life of their own — a skill entry is meaningless without the
 * student it belongs to, and it is always read and written together with the
 * rest of the profile. TRD.md section 9 embeds them as arrays for exactly this
 * reason, and his section 13 says "do not normalize or abstract the database
 * excessively." The *skill definition* is shared and normalised (the Skill
 * collection); the *student's relationship to that skill* (their level) is
 * embedded. That split is the whole design.
 *
 * The one thing this model must never do is duplicate name/email/role — those
 * belong to User, and copying them here would let the two drift.
 */

import mongoose from 'mongoose';

import {
  ACHIEVEMENT_TYPE_VALUES,
  ALLOWED_DOCUMENT_MIME_VALUES,
  DOCUMENT_TYPE_VALUES,
  EXPERIENCE_TYPE_VALUES,
  PORTFOLIO_COMPLETION_SECTIONS,
  UPLOAD_LIMITS,
  VERIFICATION_STATUSES,
  VERIFICATION_STATUS_VALUES,
} from '../constants/portfolio.js';
import {
  SKILL_LEVEL_MAX,
  SKILL_LEVEL_MIN,
  SKILL_SOURCES,
  SKILL_SOURCE_VALUES,
} from '../constants/skills.js';

/**
 * One skill a student claims, pointing at the shared catalogue entry.
 *
 * `_id: false` — a student never has the same skill twice (the service and a
 * schema validator both enforce that), so `skillId` is already the natural key
 * and a second synthetic id would only be noise in the payload.
 */
const studentSkillSchema = new mongoose.Schema(
  {
    skillId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Skill',
      required: [true, 'A skill entry must reference a skill'],
    },

    /**
     * Proficiency, 0-100 (TRD.md section 21). The frontend renders the band
     * label; the database stores the number so the assessment engine can later
     * overwrite a self-reported figure with a computed one in the same field.
     */
    level: {
      type: Number,
      required: [true, 'A skill entry must have a level'],
      min: [SKILL_LEVEL_MIN, `Level cannot be below ${SKILL_LEVEL_MIN}`],
      max: [SKILL_LEVEL_MAX, `Level cannot exceed ${SKILL_LEVEL_MAX}`],
    },

    /**
     * False until something authoritative confirms the level. Step 3 only writes
     * self-reported skills, so this stays false throughout; the assessment step
     * is what will set it true. Storing it now is what lets the UI say
     * "self-reported" honestly instead of implying verification.
     */
    verified: {
      type: Boolean,
      default: false,
    },

    /** How the level was arrived at (TRD.md section 9). Manual for every Step 3 write. */
    source: {
      type: String,
      enum: { values: SKILL_SOURCE_VALUES, message: '{VALUE} is not a valid skill source' },
      default: SKILL_SOURCES.MANUAL,
    },
  },
  { _id: false },
);

/** A career goal: a pointer into the CareerRole catalogue plus an ordering. */
const targetRoleSchema = new mongoose.Schema(
  {
    roleId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'CareerRole',
      required: [true, 'A target role must reference a career role'],
    },

    /**
     * 1 = primary goal. Lower numbers rank higher. Lets a student say "mainly a
     * backend developer, secondarily full-stack" without a separate model, and
     * gives later matching a defined order to weight by.
     */
    priority: {
      type: Number,
      default: 1,
      min: [1, 'Priority starts at 1'],
    },
  },
  { _id: false },
);

/**
 * Metadata for one stored file. THE BYTES ARE NOT HERE.
 *
 * Mongo holds only the description of the file; the file itself sits on disk
 * under `server/uploads/`, which `.gitignore` already excludes. Storing binaries
 * in the document would bloat every profile read — and a profile is read on
 * nearly every student screen — so the split is a performance decision as much
 * as a storage one.
 *
 * `fileName` is generated by the server and is the only name ever touched by the
 * filesystem. `originalName` is what the student's browser claimed, kept purely
 * so the UI can show a name they recognise and the download can suggest it. It
 * is display data, never a path — see `document.service.js`, which is the single
 * place that turns a `fileName` into a real path.
 *
 * `fileUrl` is an API route, not a static asset URL. There is no static file
 * middleware in `app.js` on purpose: serving the uploads directory statically
 * would make every student's documents readable by anyone who guessed a name.
 * Every read goes through an authenticated controller instead.
 */
const documentMetadataSchema = new mongoose.Schema(
  {
    /** Server-generated, collision-proof, safe by construction. */
    fileName: { type: String, required: true, trim: true, maxlength: 200 },

    /** What the browser claimed. Display only — never used to build a path. */
    originalName: { type: String, required: true, trim: true, maxlength: 200 },

    /** Authenticated download route for this file. */
    fileUrl: { type: String, required: true, trim: true, maxlength: 500 },

    mimeType: {
      type: String,
      required: true,
      enum: {
        values: ALLOWED_DOCUMENT_MIME_VALUES,
        message: '{VALUE} is not an accepted file type',
      },
    },

    /** Bytes actually written, measured server-side — not the claimed length. */
    size: {
      type: Number,
      required: true,
      min: [1, 'An empty file cannot be stored'],
      max: [UPLOAD_LIMITS.maxFileBytes, 'File is too large'],
    },

    documentType: {
      type: String,
      required: true,
      enum: {
        values: DOCUMENT_TYPE_VALUES,
        message: '{VALUE} is not a valid document type',
      },
    },

    uploadedAt: { type: Date, default: Date.now },
  },
  { _id: false },
);

/**
 * Verification state, factored out because five different record types need
 * exactly the same field with exactly the same default.
 *
 * `default: PENDING` with no way for a client to override it is what makes
 * "students cannot self-verify" structural. The field is absent from every
 * editable whitelist in `portfolio.validator.js`, so a request carrying
 * `verificationStatus: 'verified'` is rejected before it reaches here.
 */
const verificationStatusField = () => ({
  type: String,
  enum: {
    values: VERIFICATION_STATUS_VALUES,
    message: '{VALUE} is not a valid verification status',
  },
  default: VERIFICATION_STATUSES.PENDING,
});

/**
 * A project entry. Defined in Step 3 (TRD.md section 9) against the day the
 * portfolio step would need it; Step 6 is that day, so the fields below are an
 * extension of the original three rather than a parallel schema.
 *
 * TWO RENAMES happened here in Step 6: `projectUrl` -> `liveUrl` and
 * `repositoryUrl` -> `githubUrl`, matching the naming used across the rest of the
 * portfolio. This was safe rather than reckless: no service, controller,
 * validator, seed or client file read either name (Step 3 shipped no
 * project-editing UI and `applyEditableFields` never accepted `projects`), so no
 * stored document can contain them and no code path breaks.
 *
 * Neither URL is required. Plenty of good coursework has no public repository,
 * and demanding a GitHub link would quietly exclude the students who most need
 * the portfolio.
 */
const projectSchema = new mongoose.Schema(
  {
    title: { type: String, trim: true, maxlength: 150, required: [true, 'A project needs a title'] },

    /** Required, unlike Step 3: a titled project with no description proves nothing. */
    description: {
      type: String,
      trim: true,
      maxlength: 1000,
      required: [true, 'Describe what the project does'],
    },

    technologies: { type: [String], default: [] },

    /** What the student actually did — "Backend developer", "Team lead". */
    role: { type: String, trim: true, maxlength: 120, default: '' },

    githubUrl: { type: String, trim: true, maxlength: 500, default: '' },
    liveUrl: { type: String, trim: true, maxlength: 500, default: '' },

    startDate: { type: Date, default: null },

    /** Null while `isOngoing` is true — the two are kept consistent by a hook below. */
    endDate: { type: Date, default: null },
    isOngoing: { type: Boolean, default: false },

    /** Optional supporting file: a report, a poster, a screenshot. */
    document: { type: documentMetadataSchema, default: null },

    verificationStatus: verificationStatusField(),
  },
  { _id: true, timestamps: true },
);

